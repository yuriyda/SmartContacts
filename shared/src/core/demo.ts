// ---------------------------------------------------------------------------
// ULID-like generator — Crockford Base32, fresh IDs every rndCrockford() call,
// but stable per slot number within one buildDemoContacts() invocation via idMap.
// ---------------------------------------------------------------------------

const ENC = '0123456789ABCDEFGHJKMNPQRSTVWXYZ'

function rndCrockford(): Ulid {
  let s = ''
  for (let i = 0; i < 26; i++) s += ENC[(Math.random() * 32) | 0]!
  return s
}

// ---------------------------------------------------------------------------
// Build context
// ---------------------------------------------------------------------------

interface BuildCtx {
  locale: 'en' | 'ru'
  deviceId: string
  now: string
  idMap: Record<number, Ulid>
  defs: CustomFieldDef[]
  defIds: { coffee: Ulid; bonus: Ulid; metAt: Ulid }
}

function id(n: number, ctx: BuildCtx): Ulid {
  if (!ctx.idMap[n]) ctx.idMap[n] = rndCrockford()
  return ctx.idMap[n]!
}

function contact(slot: number, ctx: BuildCtx, lts: number, partial: Partial<Contact>): Contact {
  return {
    id: id(slot, ctx),
    createdAt: ctx.now,
    updatedAt: ctx.now,
    lamportTs: lts,
    deviceId: ctx.deviceId,
    ...partial,
  } as Contact
}

