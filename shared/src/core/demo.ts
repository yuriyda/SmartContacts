/** Build a curated 50-contact bundle for the chosen locale. Stable IDs within one call. */
export function buildDemoContacts(locale: 'en' | 'ru', deviceId: string): DemoBundle {
  const idMap: Record<number, Ulid> = {}
  const now = new Date().toISOString()
  const defs: CustomFieldDef[] = [
    {
      id: rndCrockford(),
      name: 'preferredCoffee',
      type: 'text',
      createdAt: now,
      updatedAt: now,
      lamportTs: 1,
      deviceId,
    } as CustomFieldDef,
    {
      id: rndCrockford(),
      name: 'bonusCardNumber',
      type: 'text',
      createdAt: now,
      updatedAt: now,
      lamportTs: 2,
      deviceId,
    } as CustomFieldDef,
    {
      id: rndCrockford(),
      name: 'metAt',
      type: 'date',
      createdAt: now,
      updatedAt: now,
      lamportTs: 3,
      deviceId,
    } as CustomFieldDef,
  ]
  const ctx: BuildCtx = {
    locale,
    deviceId,
    now,
    idMap,
    defs,
    defIds: { coffee: defs[0]!.id, bonus: defs[1]!.id, metAt: defs[2]!.id },
  }
  const contacts = locale === 'en' ? buildEn(ctx) : buildRu(ctx)
  // Collect distinct groups referenced in contact array
  const seenGroups = new Map<string, GroupMembership>()
  for (const c of contacts) {
    for (const g of c.groups ?? []) {
      if (!seenGroups.has(g.id)) seenGroups.set(g.id, g)
    }
  }
  return { contacts, groups: [...seenGroups.values()], customFieldDefs: defs }
}

/** Insert the demo bundle into the DB and set meta.demo_seeded = locale. Idempotent: throws if already seeded. */
export async function loadDemo(
  db: DbAdapter,
  deviceId: string,
  locale: 'en' | 'ru',
): Promise<void> {
  const seeded = await getDemoSeed(db)
  if (seeded) throw new Error(`demo data already loaded (${seeded})`)
  const bundle = buildDemoContacts(locale, deviceId)
  const repo = makeContactsRepo(db, deviceId)
  const defsRepo = makeCustomFieldDefsRepo(db, deviceId)
  // Bulk-load custom field definitions
  for (const def of bundle.customFieldDefs) await defsRepo.upsert(def)
  // Bulk-load contacts in a single transaction
  await repo.bulkLoad(bundle.contacts)
  // Mark as seeded
  await db.execute(
    `INSERT INTO meta (key, value) VALUES ('demo_seeded', ?)
     ON CONFLICT(key) DO UPDATE SET value = excluded.value`,
    [locale],
  )
}

/** Returns the seeded locale, or null if no demo data has been loaded. */
export async function getDemoSeed(db: DbAdapter): Promise<string | null> {
  const rows = await db.select<{ value: string }>("SELECT value FROM meta WHERE key='demo_seeded'")
  return rows[0]?.value ?? null
}
